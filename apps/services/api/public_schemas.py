"""
Public API Schemas — Services Catalog (customer-facing)

🔒 مستقلة تمامًا عن schemas.py الإداري: لا وراثة، ولا Union، ولا أي
   استيراد منه. الانفصال بنيوي لا اصطلاحي.

   السبب مباشر (بند 9 من تدقيق §47): في نطاق Payout كان الشكل العام
   والإداري مرتبطين عبر Union، فكفى ترتيب خاطئ لأعضائه ليُوسَّع الشكل
   العام ويُعاد حقل داخلي بقيمة null. الدرس المستخلَص أن الفصل يجب أن
   يكون على مستوى التعريف: schema عام لا يعرف حقول التسعير أصلًا لا
   يستطيع كشفها مهما أخطأت الطبقة المُسلسِلة أو تغيّر شكل الإداري.

⚠️ ممنوع إضافة room_price أو base_price أو price_per_km أو أي حقل مشتق
   منها إلى هذا الملف. العميل يرى الإجمالي النهائي وحده بعد قبول العرض
   (§36.2 — لا تفصيل بالبنود)، والكتالوج الخام بيانات إدارية.

⚠️ is_active غير موجود عمدًا أيضًا: القائمة العامة لا تعرض إلا النشط،
   فالحقل بلا معنى — وإرجاعه كان سيوحي بوجود حالة أخرى قابلة للعرض.
"""

import uuid

from ninja import Schema


class ServicePublicOut(Schema):
    """
    الشكل العام لنوع الخدمة — المعرّف والاسم والوصف فقط.

    🔒 ثلاثة حقول لا رابع لها. أي حقل يُضاف هنا مستقبلًا يجب أن يُسأل
       عنه: هل يراه العميل قبل معرفة سعره؟
    """

    id: uuid.UUID
    name: str
    description: str


class ErrorOut(Schema):
    """
    نفس شكل الخطأ المستخدم في بقية النطاقات.

    مُعرَّف هنا محليًا لا مستوردًا من schemas.py الإداري: هذا الملف يبقى
    بلا أي اعتماد على الإداري، ولو على شكل خطأ.
    """

    code: str
    detail: str
